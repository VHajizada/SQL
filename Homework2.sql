SELECT MANAGER_ID, COUNT(MANAGER_ID) AS ISCI_SAYI
FROM HR.EMPLOYEES
GROUP BY MANAGER_ID
ORDER BY ISCI_SAYI DESC;

-- Task 2:
SELECT COUNTRY_ID, COUNT(COUNTRY_ID) AS OFIS_SAYI
FROM HR.LOCATIONS
GROUP BY COUNTRY_ID
ORDER BY OFIS_SAYI DESC;

-- Task 3:
SELECT
    e.FIRST_NAME,
    e.LAST_NAME,
    j.JOB_TITLE
FROM HR.EMPLOYEES e
LEFT JOIN HR.JOBS j
    ON e.JOB_ID = j.JOB_ID;

-- Task 4:
SELECT 
    DEPARTMENT_ID,
    ROUND(AVG(SALARY), 2) AS ORTA_MAAS
FROM HR.EMPLOYEES
GROUP BY DEPARTMENT_ID
HAVING AVG(SALARY) > 8000;

-- Task 5:
SELECT
    DEPARTMENT_ID,
    COUNT(DEPARTMENT_ID) AS ISCI_SAYI
FROM HR.EMPLOYEES
WHERE SALARY >= 3000
GROUP BY DEPARTMENT_ID
HAVING COUNT(DEPARTMENT_ID) > 3;

-- Task 6:
SELECT
    j.JOB_TITLE,
    COUNT(e.EMPLOYEE_ID) AS ISCI_SAYI
FROM HR.JOBS j
LEFT JOIN HR.EMPLOYEES e
    ON j.JOB_ID = e.JOB_ID
GROUP BY j.JOB_TITLE
ORDER BY ISCI_SAYI DESC;

-- Task 7:
SELECT e.CITY, e.COUNTRY_ID 
