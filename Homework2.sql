-- Task 8:
SELECT J.JOB_TITLE,
       AVG(E.SALARY) AS ORTA_MAAS
FROM HR.EMPLOYEES E
JOIN HR.JOBS J
    ON E.JOB_ID = J.JOB_ID
GROUP BY J.JOB_TITLE
HAVING AVG(E.SALARY) > 10000; 
-- 1. E.LAST_NAME artıqdır.
-- Məqsəd hər işçinin deyil, hər vəzifənin orta maaşını göstərməkdir.

-- 2. JOIN şərtində J.JOB_ID yazılmalıdır.
-- JOB_ID sütununun hansı cədvələ aid olduğu göstərilməli idi.
-- Düzgün: ON E.JOB_ID = J.JOB_ID

-- 3. WHERE əvəzinə HAVING istifadə edilməlidir.
-- Çünki AVG() aqreqat funksiyasıdır və qruplaşdırmadan
-- sonra orta maaşa görə filtr tətbiq edilməlidir.


-- Task 9:
SELECT L.CITY,
       COUNT(L.CITY) AS ISCI_SAYI,
       ROUND(AVG(E.SALARY)) AS ORTA_MAAS
FROM HR.EMPLOYEES E
JOIN HR.DEPARTMENTS D
    ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
JOIN HR.LOCATIONS L
    ON D.LOCATION_ID = L.LOCATION_ID
GROUP BY L.CITY
HAVING COUNT(L.CITY) > 5
ORDER BY ISCI_SAYI DESC;

-- Task 10:
SELECT D.DEPARTMENT_NAME,
       COUNT(e.employee_id) AS ISCI_SAYI
FROM HR.DEPARTMENTS D
LEFT JOIN HR.EMPLOYEES E
    ON D.DEPARTMENT_ID = E.DEPARTMENT_ID
GROUP BY D.DEPARTMENT_NAME
ORDER BY ISCI_SAYI DESC, D.DEPARTMENT_NAME ASC;
