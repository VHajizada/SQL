-- TASK 1

SELECT FIRST_NAME, LAST_NAME, DEPARTMENT_ID
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID IN (
    SELECT DEPARTMENT_ID
    FROM HR.DEPARTMENTS
    WHERE DEPARTMENT_NAME IN ('Marketing', 'Purchasing', 'IT')
);

SELECT E.FIRST_NAME, E.LAST_NAME, E.DEPARTMENT_ID
FROM HR.EMPLOYEES E
WHERE EXISTS (
    SELECT 1
    FROM HR.DEPARTMENTS D
    WHERE D.DEPARTMENT_ID = E.DEPARTMENT_ID
    AND D.DEPARTMENT_NAME IN ('Marketing', 'Purchasing', 'IT')
);


-- TASK 2

SELECT M.EMPLOYEE_ID, M.FIRST_NAME, M.LAST_NAME
FROM HR.EMPLOYEES M
WHERE EXISTS (
    SELECT 1
    FROM HR.EMPLOYEES E
    WHERE M.EMPLOYEE_ID = E.MANAGER_ID
);


-- TASK 3

SELECT
    TO_CHAR(TO_DATE('2026/12/31', 'YYYY/MM/DD'), 'DD.MM.YYYY HH24:MI') AS A,
    TO_CHAR(TO_DATE('31-12-2026 23:59', 'DD-MM-YYYY HH24:MI'), 'DD.MM.YYYY HH24:MI') AS B,
    TO_CHAR(TO_DATE('20261231', 'YYYYMMDD'), 'DD.MM.YYYY HH24:MI') AS C,
    TO_CHAR(TO_DATE('December 31, 2026', 'Month DD, YYYY'), 'DD.MM.YYYY HH24:MI') AS D,
    TO_CHAR(TO_DATE('2026@12@31  08:30', 'YYYY@MM@DD HH24:MI'), 'DD.MM.YYYY HH24:MI') AS E
FROM DUAL;


-- TASK 4

SELECT FIRST_NAME, LAST_NAME, HIRE_DATE
FROM HR.EMPLOYEES
WHERE HIRE_DATE >= DATE '2008-01-01'
ORDER BY HIRE_DATE ASC;

SELECT FIRST_NAME, LAST_NAME, HIRE_DATE
FROM HR.EMPLOYEES
WHERE HIRE_DATE >= TO_DATE('2008-01-01', 'YYYY-MM-DD')
ORDER BY HIRE_DATE ASC;


-- TASK 5

SELECT E.EMPLOYEE_ID, E.FIRST_NAME, E.LAST_NAME, E.DEPARTMENT_ID
FROM HR.EMPLOYEES E
WHERE NOT EXISTS (
    SELECT 1
    FROM HR.DEPARTMENTS D
    WHERE E.DEPARTMENT_ID = D.DEPARTMENT_ID
);

SELECT EMPLOYEE_ID, FIRST_NAME, LAST_NAME, DEPARTMENT_ID
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID NOT IN (
    SELECT DEPARTMENT_ID
    FROM HR.DEPARTMENTS
);

SELECT EMPLOYEE_ID, FIRST_NAME, LAST_NAME, DEPARTMENT_ID
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID NOT IN (
    SELECT DEPARTMENT_ID
    FROM HR.DEPARTMENTS
    WHERE DEPARTMENT_ID IS NOT NULL
)
OR DEPARTMENT_ID IS NULL;
